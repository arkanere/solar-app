// Regenerates tests/schema/000-baseline.sql — the table DDL the test database
// starts from.
//
// Why a baseline exists at all: the numbered SQL migrations in
// apps/main-app/src/lib/server/migrations/ only go back as far as the migrations
// convention does. 36 of the 55 tables — including leaddata, businesses_1,
// business_profiles and leaddata_claimrequests — were created before that and
// have no CREATE TABLE anywhere in the repo (`branches` was one of them until
// 078 dropped it). Replaying the
// migrations against an empty database therefore fails at 034.
//
// So the test schema is built in two steps: this baseline creates the tables,
// then the numbered migrations replay on top to install the sv_sync_* functions,
// the triggers and the seed rows (countries, etc.) that no introspected schema
// can capture. The migrations are written with IF NOT EXISTS / CREATE OR REPLACE
// / ON CONFLICT DO NOTHING, so replaying them over the baseline is a no-op for
// everything the baseline already has.
//
// The DDL comes from packages/db/src/schema, which is itself produced by
// `drizzle-kit pull` against the live database — so the baseline traces back to
// production, not to a hand-written guess. `export` only reads the schema file;
// it never connects to a database, so this does not violate the introspection-only
// rule in packages/db/drizzle.config.ts (which is about never letting drizzle-kit
// own the production schema).
//
// Usage: node scripts/generate-test-baseline.mjs

import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const outFile = join(root, 'tests/schema/000-baseline.sql');

const raw = execFileSync(
	'npx',
	['drizzle-kit', 'export', '--dialect', 'postgresql', '--schema', 'packages/db/src/schema/index.ts'],
	{ cwd: root, encoding: 'utf8', maxBuffer: 32 * 1024 * 1024 }
);

// Strip per-column operator classes from index definitions.
//
// drizzle-kit's introspection records an opclass per indexed column but does not
// keep them aligned with the columns, so the exported DDL contains combinations
// Postgres rejects outright — `"country_code" text_ops` on a char column, for
// instance. The opclasses are pure optimisation metadata and every one of these
// indexes is valid with the column's default opclass, so they are dropped.
let cleaned = raw.replace(/("[^"]+")\s+[a-z0-9_]+_ops\b/g, '$1');

// Drop expression indexes that call loc_key().
//
// loc_key() is a legacy database function defined nowhere in this repo — it
// exists only in the live database, predating the migrations convention like the
// tables in the paragraph above. drizzle-kit pull records the indexes that use it
// but not the function itself, so these three statements cannot be replayed.
// All three are on masterlist_* tables, which no application query touches; the
// indexes are an admin-tooling optimisation and their absence changes no result.
// If a test ever needs those tables, the fix is to add the function definition
// here rather than to widen this filter.
cleaned = cleaned
	.split('\n')
	.filter((line) => !(/^CREATE (UNIQUE )?INDEX/.test(line) && line.includes('loc_key(')))
	.join('\n');

const header = `-- GENERATED by scripts/generate-test-baseline.mjs — do not hand-edit.
--
-- Table DDL for the integration test database, exported from packages/db/src/schema
-- (which drizzle-kit pull produces from the live database). Applied by the test
-- global setup before the numbered SQL migrations replay on top of it.
--
-- Regenerate after a schema change:
--   npm run pull -w @solar/db && node scripts/generate-test-baseline.mjs

`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, header + cleaned);
console.log(`Wrote ${outFile}`);
